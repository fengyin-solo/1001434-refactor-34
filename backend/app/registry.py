"""模块注册表：18 个业务模块的状态序列、动作规则与负向动作集中在这里。

以前这些常量分散在各模块的 service 里，概览、模块页各抄一份，改口径要挨个入口核对。
现在规则只有这一份：service 流转、metrics 统计、seed 生成全部从这里取。
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class ModuleSpec:
    """一个业务模块的流转规则：状态序列末位为终态，负向动作的目标状态计入异常。"""

    key: str
    label: str
    required_fields: tuple[str, ...]
    status_order: tuple[str, ...]
    action_rules: dict[str, str]
    negative_actions: tuple[str, ...] = ()

    @property
    def terminal_status(self) -> str:
        """终态：状态序列末位，进入终态的记录不再算待处理。"""
        return self.status_order[-1]

    @property
    def abnormal_statuses(self) -> frozenset[str]:
        """异常状态集：负向动作（作废、停用等）会把记录推进这些状态。"""
        return frozenset(self.action_rules[action] for action in self.negative_actions)


def _spec(
    key: str,
    label: str,
    required_fields: tuple[str, ...],
    status_order: tuple[str, ...],
    action_rules: dict[str, str],
    negative_actions: tuple[str, ...] = (),
) -> ModuleSpec:
    return ModuleSpec(
        key=key,
        label=label,
        required_fields=required_fields,
        status_order=status_order,
        action_rules=action_rules,
        negative_actions=negative_actions,
    )


