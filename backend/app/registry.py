SPEC_BY_KEY: dict[str, ModuleSpec] = {spec.key: spec for spec in MODULE_SPECS}


def get_spec(key: str) -> ModuleSpec:
    """按模块 key 取规则；未注册的模块直接报出来，而不是静默跳过。"""
    try:
        return SPEC_BY_KEY[key]
    except KeyError:
        raise KeyError(f"模块「{key}」未在注册表登记，请先在 app/registry.py 补充规则") from None
